function dbErrorToField(message: string): FieldErrors | null {
  if (message.includes("employees_email_lower")) return { email: "Another employee already uses this email" };
  if (message.includes("employee_statutory_pan_key")) return { pan: "This PAN is already recorded for another employee" };
  if (message.includes("employee_statutory_aadhaar_key")) return { aadhaar: "This Aadhaar is already recorded for another employee" };
  if (message.includes("at_least_18_on_joining")) return { dob: "Employee must be at least 18 years old on the joining date" };
  if (message.includes("reporting loop")) return { reporting_manager_id: "Invalid reporting manager: this creates a reporting loop" };
  return null;
}

async function checkManager(employeeId: string | null, managerId: string, today: string): Promise<string | null> {
  if (!managerId) return null;
  const { employees } = await loadOrgData();
  const mgr = employees.find((e) => e.id === managerId);
  if (!mgr || !isActiveOn(mgr, today)) return "Pick an active employee as reporting manager";
  const managerOf = new Map(employees.map((e) => [e.id, e.reporting_manager_id]));
  if (createsReportingLoop(employeeId, managerId, managerOf)) {
    return "Invalid reporting manager: an employee cannot report to themselves or to someone who reports to them";
  }
  return null;
}

/** E1 — HR adds an employee. The code (KCF0001…) is generated by the database. */
export async function createEmployee(raw: EmployeeInput): Promise<ActionResult<{ id: string; code: string }>> {
  const s = await requireHr();
  const input = normaliseIds(raw);
  const fieldErrors = validateEmployee(input, "create");
  const mgrErr = await checkManager(null, input.reporting_manager_id, s.today);
  if (mgrErr) fieldErrors.reporting_manager_id = mgrErr;
  if (Object.keys(fieldErrors).length) return { ok: false, error: "Please fix the highlighted fields", fieldErrors };

  const { data, error } = await db().rpc("create_employee", { p: input, p_actor: s.employeeId });
  if (error) {
    const fe = dbErrorToField(error.message);
    return fe ? { ok: false, error: "Please fix the highlighted fields", fieldErrors: fe } : { ok: false, error: error.message };
  }
  const created = data as Employee;
  revalidatePath("/employees");
  return { ok: true, data: { id: created.id, code: created.employee_code }, message: `Saved as ${created.employee_code}` };
}

const TRACKED: (keyof Employee)[] = [
  "full_name", "email", "mobile", "dob", "gender", "address_line", "city", "state", "pin_code",
  "date_of_joining", "designation", "grade", "department_id", "location_id", "reporting_manager_id", "is_hr_admin",
  "emergency_name", "emergency_relation", "emergency_mobile",
];

/** E1/E8 — HR edits an employee. Every changed job/statutory field is written to the audit log. */
export async function updateEmployee(id: string, raw: EmployeeInput): Promise<ActionResult> {
  const s = await requireHr();
  const input = normaliseIds(raw);
  const fieldErrors = validateEmployee(input, "edit");
  const mgrErr = await checkManager(id, input.reporting_manager_id, s.today);
  if (mgrErr) fieldErrors.reporting_manager_id = mgrErr;
  if (id === s.employeeId && !input.is_hr_admin) fieldErrors.is_hr_admin = "You cannot remove your own HR Admin access";
  if (Object.keys(fieldErrors).length) return { ok: false, error: "Please fix the highlighted fields", fieldErrors };

  const sb = db();
  const { employees, departments, locations } = await loadOrgData();
  const before = employees.find((e) => e.id === id);
  if (!before) return { ok: false, error: "Employee not found" };

  const nameOf = (field: string, value: unknown) => {
    if (value === null || value === undefined || value === "") return null;
    if (field === "department_id") return departments.find((d) => d.id === value)?.name ?? String(value);
    if (field === "location_id") return locations.find((l) => l.id === value)?.name ?? String(value);
    if (field === "reporting_manager_id") return employees.find((e) => e.id === value)?.full_name ?? String(value);
    return String(value);
  };

  const patch: Record<string, unknown> = {};
  const audit: AuditInput[] = [];
  for (const f of TRACKED) {
    const next = (input as unknown as Record<string, unknown>)[f];
    const normNext = next === "" ? null : next;
    const prev = before[f] === "" ? null : before[f];
    if (String(prev ?? "") !== String(normNext ?? "")) {
      patch[f] = normNext;
      audit.push({ table_name: "employees", record_id: id, field: f.replace(/_id$/, ""), old_value: nameOf(f, prev), new_value: nameOf(f, normNext), changed_by: s.employeeId });
    }
  }

  if (Object.keys(patch).length) {
    const { error } = await sb.from("employees").update(patch).eq("id", id);
    if (error) {
      const fe = dbErrorToField(error.message);
      return fe ? { ok: false, error: "Please fix the highlighted fields", fieldErrors: fe } : { ok: false, error: error.message };
    }
  }

  // Statutory and bank: only fields HR typed in are changed. Audit stores masked values only.
  const stat = must(await sb.from("employee_statutory").select("*").eq("employee_id", id).maybeSingle(), "statutory") as
    { pan: string; aadhaar: string; uan: string | null } | null;
  const statPatch: Record<string, string | null> = {};
  if (input.pan && input.pan !== stat?.pan) {
    statPatch.pan = input.pan;
    audit.push({ table_name: "employee_statutory", record_id: id, field: "pan", old_value: maskPan(stat?.pan), new_value: maskPan(input.pan), changed_by: s.employeeId });
  }
  if (input.aadhaar && input.aadhaar !== stat?.aadhaar) {
    statPatch.aadhaar = input.aadhaar;
    audit.push({ table_name: "employee_statutory", record_id: id, field: "aadhaar", old_value: maskAadhaar(stat?.aadhaar), new_value: maskAadhaar(input.aadhaar), changed_by: s.employeeId });
  }
  if (input.uan && input.uan !== stat?.uan) {
    statPatch.uan = input.uan;
    audit.push({ table_name: "employee_statutory", record_id: id, field: "uan", old_value: maskUan(stat?.uan), new_value: maskUan(input.uan), changed_by: s.employeeId });
  }
  if (Object.keys(statPatch).length) {
    const { error } = await sb.from("employee_statutory").update(statPatch).eq("employee_id", id);
    if (error) {
      const fe = dbErrorToField(error.message);
      return fe ? { ok: false, error: "Please fix the highlighted fields", fieldErrors: fe } : { ok: false, error: error.message };
    }
  }

  const bank = must(await sb.from("employee_bank").select("*").eq("employee_id", id).maybeSingle(), "bank") as
    { account_number: string; ifsc: string; bank_name: string } | null;
  const bankPatch: Record<string, string> = {};
  if (input.account_number && input.account_number !== bank?.account_number) {
    bankPatch.account_number = input.account_number;
    audit.push({ table_name: "employee_bank", record_id: id, field: "account_number", old_value: maskAccount(bank?.account_number), new_value: maskAccount(input.account_number), changed_by: s.employeeId });
  }
  if (input.ifsc && input.ifsc !== bank?.ifsc) {
    bankPatch.ifsc = input.ifsc;
    audit.push({ table_name: "employee_bank", record_id: id, field: "ifsc", old_value: bank?.ifsc ?? null, new_value: input.ifsc, changed_by: s.employeeId });
  }
  if (input.bank_name && input.bank_name !== bank?.bank_name) {
    bankPatch.bank_name = input.bank_name;
    audit.push({ table_name: "employee_bank", record_id: id, field: "bank_name", old_value: bank?.bank_name ?? null, new_value: input.bank_name, changed_by: s.employeeId });
  }
  if (Object.keys(bankPatch).length) {
    must(await sb.from("employee_bank").update(bankPatch).eq("employee_id", id).select("employee_id"), "update bank");
  }

  await writeAudit(audit);
  revalidatePath(`/employees/${id}`);
  revalidatePath("/employees");
  return { ok: true, message: audit.length ? `Saved ${audit.length} change${audit.length > 1 ? "s" : ""}` : "No changes" };
}

/** E5 — self-service: phone, address and emergency contact only. Job fields cannot be sent here. */
export async function updateContact(id: string, raw: ContactInput): Promise<ActionResult> {
  const s = await requireSession();
  if (id !== s.employeeId && !s.isHr) return { ok: false, error: "You can only edit your own contact details" };
  const input = normaliseIds({
    mobile: raw.mobile, address_line: raw.address_line, city: raw.city, state: raw.state, pin_code: raw.pin_code,
    emergency_name: raw.emergency_name, emergency_relation: raw.emergency_relation, emergency_mobile: raw.emergency_mobile,
  });
  const fieldErrors = validateContact(input);
  if (Object.keys(fieldErrors).length) return { ok: false, error: "Please fix the highlighted fields", fieldErrors };

  const sb = db();
  const before = must(await sb.from("employees").select("*").eq("id", id).single(), "employee") as Employee;
  const audit: AuditInput[] = [];
  for (const [k, v] of Object.entries(input)) {
    const prev = (before as unknown as Record<string, unknown>)[k];
    if (String(prev ?? "") !== String(v ?? "")) {
      audit.push({ table_name: "employees", record_id: id, field: k, old_value: (prev as string) ?? null, new_value: v, changed_by: s.employeeId });
    }
  }
  must(await sb.from("employees").update(input).eq("id", id).select("id"), "update contact");
  await writeAudit(audit);
  revalidatePath(`/employees/${id}`);
  revalidatePath("/profile");
  return { ok: true, message: "Contact details saved" };
}

/** E6 — deactivate with a last working day. The record is never deleted. */
export async function deactivateEmployee(id: string, lastWorkingDay: string, reason: string): Promise<ActionResult> {
  const s = await requireHr();
  if (id === s.employeeId) return { ok: false, error: "You cannot deactivate yourself" };
  if (!isValidISODate(lastWorkingDay)) return { ok: false, error: "Pick the last working day" };
  if (!reason || reason.trim().length < 3) return { ok: false, error: "Enter a reason for the exit" };
  const sb = db();
  const emp = must(await sb.from("employees").select("*").eq("id", id).single(), "employee") as Employee;
  if (lastWorkingDay < emp.date_of_joining) return { ok: false, error: "Last working day cannot be before the joining date" };
  const reports = must(
    await sb.from("employees").select("id, full_name, last_working_day").eq("reporting_manager_id", id),
    "reports",
  ) as { id: string; full_name: string; last_working_day: string | null }[];
  const stillActive = reports.filter((r) => !r.last_working_day || r.last_working_day > lastWorkingDay);
  if (stillActive.length) {
    return { ok: false, error: `Reassign ${stillActive.length} direct report(s) first: ${stillActive.map((r) => r.full_name).join(", ")}` };
  }
  must(await sb.from("employees").update({ last_working_day: lastWorkingDay }).eq("id", id).select("id"), "deactivate");
  await writeAudit([{ table_name: "employees", record_id: id, field: "last_working_day", old_value: emp.last_working_day, new_value: lastWorkingDay, action: "deactivate", reason: reason.trim(), changed_by: s.employeeId }]);
  revalidatePath(`/employees/${id}`);
  revalidatePath("/employees");
  return { ok: true, message: `Deactivated. ${emp.full_name} can log in until ${lastWorkingDay}.` };
}

export async function cancelDeactivation(id: string): Promise<ActionResult> {
  const s = await requireHr();
  const sb = db();
  const emp = must(await sb.from("employees").select("*").eq("id", id).single(), "employee") as Employee;
  if (!emp.last_working_day) return { ok: true };
  must(await sb.from("employees").update({ last_working_day: null }).eq("id", id).select("id"), "reactivate");
  await writeAudit([{ table_name: "employees", record_id: id, field: "last_working_day", old_value: emp.last_working_day, new_value: null, action: "update", reason: "Deactivation cancelled", changed_by: s.employeeId }]);
  revalidatePath(`/employees/${id}`);
  return { ok: true, message: "Deactivation cancelled" };
}

/** E7 — HR-only reveal of PAN or bank account. Logged. Aadhaar can never be revealed. */
export async function revealSensitive(id: string, field: "pan" | "account_number"): Promise<ActionResult<{ value: string }>> {
  const s = await requireHr();
  if (field !== "pan" && field !== "account_number") return { ok: false, error: "This field cannot be revealed" };
  const sb = db();
  const value =
    field === "pan"
      ? ((must(await sb.from("employee_statutory").select("pan").eq("employee_id", id).single(), "pan") as { pan: string }).pan)
      : ((must(await sb.from("employee_bank").select("account_number").eq("employee_id", id).single(), "bank") as { account_number: string }).account_number);
  await writeAudit([{ table_name: field === "pan" ? "employee_statutory" : "employee_bank", record_id: id, field, action: "reveal", changed_by: s.employeeId }]);
  return { ok: true, data: { value } };
}
